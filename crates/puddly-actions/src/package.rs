//! Packaging B — copy the action sidecar into `.puddly/generated/` (Step 13).

use crate::error::{ActionError, ActionResult};
use crate::ipc::{find_sidecar_workspace, DEFAULT_SIDECAR_SCRIPT, GENERATED_SIDECAR_SCRIPT};
use std::fs;
use std::path::{Path, PathBuf};

/// Copy `tools/puddly-action-sidecar.mjs` (found via walk-up) into
/// `<app_root>/.puddly/generated/action-sidecar.mjs`.
///
/// Action entrypoints stay at their source paths (absolute `sourcePath` on the wire).
pub fn package_action_sidecar(app_root: &Path) -> ActionResult<PathBuf> {
    let template = resolve_sidecar_template(app_root)?;
    let dest = app_root.join(GENERATED_SIDECAR_SCRIPT);
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent).map_err(|e| {
            ActionError::msg(format!("create {}: {e}", parent.display()))
        })?;
    }
    let bytes = fs::read(&template)
        .map_err(|e| ActionError::msg(format!("read sidecar template {}: {e}", template.display())))?;
    // Rewrite the banner so generated copies are recognizable; keep body identical.
    let body = String::from_utf8_lossy(&bytes);
    let generated = if body.contains("Puddly action sidecar") {
        body.replacen(
            "Puddly action sidecar",
            "Puddly action sidecar (generated — do not edit; run `puddly build`)",
            1,
        )
    } else {
        format!(
            "/** Generated by `puddly build` from {} — do not edit. */\n{}",
            template.display(),
            body
        )
    };
    fs::write(&dest, generated.as_bytes())
        .map_err(|e| ActionError::msg(format!("write {}: {e}", dest.display())))?;
    Ok(dest)
}

fn resolve_sidecar_template(app_root: &Path) -> ActionResult<PathBuf> {
    if let Some(ws) = find_sidecar_workspace(app_root) {
        let p = ws.join(DEFAULT_SIDECAR_SCRIPT);
        if p.is_file() {
            return Ok(p);
        }
    }
    let local = app_root.join(DEFAULT_SIDECAR_SCRIPT);
    if local.is_file() {
        return Ok(local);
    }
    Err(ActionError::msg(format!(
        "sidecar template not found (looked for {DEFAULT_SIDECAR_SCRIPT} from {})",
        app_root.display()
    )))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn package_writes_generated_sidecar() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .canonicalize()
            .unwrap();
        let app = root.join("examples/todo-slice");
        let dest = package_action_sidecar(&app).expect("package");
        assert!(dest.is_file());
        assert!(dest.ends_with("action-sidecar.mjs"));
        let text = fs::read_to_string(&dest).unwrap();
        assert!(text.contains("generated"));
        assert!(text.contains("PROTOCOL_VERSION"));
        let _ = fs::remove_file(&dest);
    }
}

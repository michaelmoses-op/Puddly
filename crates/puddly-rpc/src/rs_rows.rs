//! Generate typed Rust row structs from IR into `.puddly/generated/` (ADR-042 / Step 24).
//!
//! `DbRow` maps remain the executor boundary; generated structs decode above that layer.

use puddly_ir::{AppIr, FieldIr, FieldKind, ResourceIr};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Relative path under the app root (gitignored via `.puddly/generated/`).
pub const GENERATED_ROWS_RS: &str = ".puddly/generated/rows.rs";

/// Render `rows.rs` source for `ir` (deterministic resource / field order).
pub fn generate_rs_rows(ir: &AppIr) -> String {
    let mut out = String::new();
    out.push_str("//! Generated by `puddly build` / `puddly client generate` — do not edit.\n");
    out.push_str("//! Typed rows decode [`puddly_db::DbRow`] maps; the executor still returns maps.\n\n");
    out.push_str("use puddly_db::{DbRow, SqlValue};\n\n");

    out.push_str("/// Decode failure when a column is missing or the wrong [`SqlValue`] variant.\n");
    out.push_str("#[derive(Debug, Clone, PartialEq, Eq)]\n");
    out.push_str("pub enum RowDecodeError {\n");
    out.push_str("    Missing(&'static str),\n");
    out.push_str("    Type(&'static str),\n");
    out.push_str("}\n\n");
    out.push_str("impl std::fmt::Display for RowDecodeError {\n");
    out.push_str("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n");
    out.push_str("        match self {\n");
    out.push_str("            Self::Missing(c) => write!(f, \"missing column `{c}`\"),\n");
    out.push_str("            Self::Type(c) => write!(f, \"wrong type for column `{c}`\"),\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
    out.push_str("impl std::error::Error for RowDecodeError {}\n\n");

    out.push_str(HELPERS);

    for r in &ir.resources {
        out.push_str(&resource_row_struct(r));
        out.push('\n');
    }

    out
}

const HELPERS: &str = r#"fn require_string(row: &DbRow, col: &'static str) -> Result<String, RowDecodeError> {
    match row.get(col) {
        Some(SqlValue::Text(s) | SqlValue::Uuid(s)) => Ok(s.clone()),
        Some(SqlValue::Null) | None => Err(RowDecodeError::Missing(col)),
        Some(_) => Err(RowDecodeError::Type(col)),
    }
}

fn optional_string(row: &DbRow, col: &'static str) -> Result<Option<String>, RowDecodeError> {
    match row.get(col) {
        None | Some(SqlValue::Null) => Ok(None),
        Some(SqlValue::Text(s) | SqlValue::Uuid(s)) => Ok(Some(s.clone())),
        Some(_) => Err(RowDecodeError::Type(col)),
    }
}

fn require_bool(row: &DbRow, col: &'static str) -> Result<bool, RowDecodeError> {
    match row.get(col) {
        Some(SqlValue::Bool(b)) => Ok(*b),
        Some(SqlValue::Null) | None => Err(RowDecodeError::Missing(col)),
        Some(_) => Err(RowDecodeError::Type(col)),
    }
}

fn optional_bool(row: &DbRow, col: &'static str) -> Result<Option<bool>, RowDecodeError> {
    match row.get(col) {
        None | Some(SqlValue::Null) => Ok(None),
        Some(SqlValue::Bool(b)) => Ok(Some(*b)),
        Some(_) => Err(RowDecodeError::Type(col)),
    }
}

"#;

fn resource_type_name(resource: &str) -> String {
    let mut chars = resource.chars();
    match chars.next() {
        None => "Resource".into(),
        Some(c) => format!("{}{}", c.to_ascii_uppercase(), chars.as_str()),
    }
}

/// `dueDate` → `due_date` for Rust idents; column lookup keeps the IR name.
fn to_snake_case(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn field_is_optional(f: &FieldIr) -> bool {
    f.options.optional == Some(true) || f.options.auto == Some(true)
}

fn rust_field_type(kind: &FieldKind, optional: bool) -> &'static str {
    match (kind, optional) {
        (FieldKind::Bool, false) => "bool",
        (FieldKind::Bool, true) => "Option<bool>",
        (
            FieldKind::Id
            | FieldKind::Text
            | FieldKind::Date
            | FieldKind::Timestamp
            | FieldKind::Ref { .. },
            false,
        ) => "String",
        (
            FieldKind::Id
            | FieldKind::Text
            | FieldKind::Date
            | FieldKind::Timestamp
            | FieldKind::Ref { .. },
            true,
        ) => "Option<String>",
        (FieldKind::Computed { .. }, _) => "()", // skipped by caller
    }
}

fn resource_row_struct(r: &ResourceIr) -> String {
    let type_name = format!("{}Row", resource_type_name(&r.name));
    let mut s = String::new();
    s.push_str("#[derive(Debug, Clone, PartialEq)]\n");
    s.push_str(&format!("pub struct {type_name} {{\n"));

    let mut decode_arms = String::new();
    for f in &r.fields {
        if matches!(f.kind, FieldKind::Computed { .. }) {
            continue;
        }
        let optional = field_is_optional(f);
        let rust_name = to_snake_case(&f.name);
        let ty = rust_field_type(&f.kind, optional);
        s.push_str(&format!("    pub {rust_name}: {ty},\n"));

        let col = &f.name;
        let helper = match (&f.kind, optional) {
            (FieldKind::Bool, false) => format!("require_bool(row, \"{col}\")?"),
            (FieldKind::Bool, true) => format!("optional_bool(row, \"{col}\")?"),
            (_, false) => format!("require_string(row, \"{col}\")?"),
            (_, true) => format!("optional_string(row, \"{col}\")?"),
        };
        decode_arms.push_str(&format!("            {rust_name}: {helper},\n"));
    }

    s.push_str("}\n\n");
    s.push_str(&format!("impl {type_name} {{\n"));
    s.push_str("    pub fn from_db_row(row: &DbRow) -> Result<Self, RowDecodeError> {\n");
    s.push_str("        Ok(Self {\n");
    s.push_str(&decode_arms);
    s.push_str("        })\n");
    s.push_str("    }\n");
    s.push_str("}\n");
    s
}

/// Write [`GENERATED_ROWS_RS`] under `app_root`.
pub fn write_rs_rows(app_root: &Path, ir: &AppIr) -> io::Result<PathBuf> {
    let dest = app_root.join(GENERATED_ROWS_RS);
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&dest, generate_rs_rows(ir))?;
    Ok(dest)
}

#[cfg(test)]
mod unit {
    use super::*;

    #[test]
    fn snake_case_from_camel() {
        assert_eq!(to_snake_case("dueDate"), "due_date");
        assert_eq!(to_snake_case("id"), "id");
        assert_eq!(to_snake_case("createdAt"), "created_at");
    }
}

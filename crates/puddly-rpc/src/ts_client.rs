//! Generate a small typed TypeScript RPC client from IR (ADR-038 / Step 20).

use puddly_ir::{AppIr, FieldKind, ResourceIr};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Relative path under the app root (gitignored via `.puddly/generated/`).
pub const GENERATED_CLIENT_TS: &str = ".puddly/generated/client.ts";

/// Render `client.ts` source for `ir` (deterministic field / resource order).
pub fn generate_ts_client(ir: &AppIr) -> String {
    let mut out = String::new();
    out.push_str("/**\n");
    out.push_str(" * Generated by `puddly client generate` / `puddly build` — do not edit.\n");
    out.push_str(" * Uses fetch + X-Puddly-CSRF + credentials: \"include\" (same as islands RPC).\n");
    out.push_str(" */\n\n");

    out.push_str("export type RpcErrorBody = {\n");
    out.push_str("  code: string;\n");
    out.push_str("  message: string;\n");
    out.push_str("  status?: number;\n");
    out.push_str("};\n\n");

    out.push_str("export type RpcResult<T = unknown> = {\n");
    out.push_str("  ok: boolean;\n");
    out.push_str("  data?: T;\n");
    out.push_str("  error?: RpcErrorBody;\n");
    out.push_str("};\n\n");

    out.push_str("export type ClientOptions = {\n");
    out.push_str("  /** Origin or path prefix (no trailing slash). Default: \"\". */\n");
    out.push_str("  baseUrl?: string;\n");
    out.push_str("  fetch?: typeof fetch;\n");
    out.push_str("};\n\n");

    for r in &ir.resources {
        out.push_str(&resource_fields_type(r));
        out.push('\n');
    }

    out.push_str(
        r#"function createRpc(opts: ClientOptions = {}) {
  const base = (opts.baseUrl ?? "").replace(/\/$/, "");
  const f = opts.fetch ?? fetch;
  return async function rpc<T = unknown>(
    operation: string,
    body?: Record<string, unknown>,
  ): Promise<RpcResult<T>> {
    try {
      const res = await f(`${base}/rpc/${operation}`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "X-Puddly-CSRF": "1",
        },
        credentials: "include",
        body: JSON.stringify(body ?? {}),
      });
      const json = (await res.json()) as RpcResult<T>;
      return json;
    } catch (e) {
      const message = e instanceof Error ? e.message : String(e);
      return { ok: false, error: { code: "network", message } };
    }
  };
}

"#,
    );

    out.push_str("export function createClient(opts: ClientOptions = {}) {\n");
    out.push_str("  const rpc = createRpc(opts);\n");
    out.push_str("  return {\n");

    out.push_str("    auth: {\n");
    out.push_str(
        "      login: (body?: { email?: string; password?: string }) => rpc(\"auth.login\", body),\n",
    );
    out.push_str(
        "      register: (body?: { email?: string; password?: string }) => rpc(\"auth.register\", body),\n",
    );
    out.push_str("      logout: (body?: Record<string, unknown>) => rpc(\"auth.logout\", body),\n");
    out.push_str("    },\n");

    for r in &ir.resources {
        let name = &r.name;
        let type_name = resource_type_name(name);
        out.push_str(&format!("    {name}: {{\n"));
        out.push_str(&format!(
            "      list: (body?: Record<string, unknown>) => rpc<{type_name}ListResult>(\"{name}.list\", body),\n"
        ));
        out.push_str(&format!(
            "      get: (body: {{ id: string }} & Record<string, unknown>) => rpc<{type_name}Fields>(\"{name}.get\", body),\n"
        ));
        out.push_str(&format!(
            "      create: (body?: Partial<{type_name}Fields>) => rpc(\"{name}.create\", body),\n"
        ));
        out.push_str(&format!(
            "      update: (body: {{ id: string }} & Partial<{type_name}Fields>) => rpc(\"{name}.update\", body),\n"
        ));
        out.push_str(&format!(
            "      delete: (body: {{ id: string }}) => rpc(\"{name}.delete\", body),\n"
        ));
        for action in &r.actions {
            let an = &action.name;
            out.push_str(&format!(
                "      {an}: (body?: Record<string, unknown>) => rpc(\"{name}.{an}\", body),\n"
            ));
        }
        out.push_str("    },\n");
    }

    out.push_str("  } as const;\n");
    out.push_str("}\n\n");
    out.push_str("/** Default client bound to same-origin `/rpc/*`. */\n");
    out.push_str("export const api = createClient();\n");
    out
}

fn resource_type_name(resource: &str) -> String {
    let mut chars = resource.chars();
    match chars.next() {
        None => "Resource".into(),
        Some(c) => format!("{}{}", c.to_ascii_uppercase(), chars.as_str()),
    }
}

fn resource_fields_type(r: &ResourceIr) -> String {
    let type_name = resource_type_name(&r.name);
    let mut s = format!("export type {type_name}Fields = {{\n");
    for f in &r.fields {
        if matches!(f.kind, FieldKind::Computed { .. }) {
            continue;
        }
        let ts = field_ts_type(&f.kind);
        let optional = f.options.optional == Some(true) || f.options.auto == Some(true);
        if optional {
            s.push_str(&format!("  {}?: {};\n", f.name, ts));
        } else {
            s.push_str(&format!("  {}: {};\n", f.name, ts));
        }
    }
    s.push_str("};\n\n");
    s.push_str(&format!(
        "export type {type_name}ListResult = {{\n  items: {type_name}Fields[];\n  limit: number;\n}};\n"
    ));
    s
}

fn field_ts_type(kind: &FieldKind) -> &'static str {
    match kind {
        FieldKind::Bool => "boolean",
        FieldKind::Id
        | FieldKind::Text
        | FieldKind::Date
        | FieldKind::Timestamp
        | FieldKind::Ref { .. } => "string",
        FieldKind::Computed { .. } => "unknown",
    }
}

/// Write [`GENERATED_CLIENT_TS`] under `app_root`.
pub fn write_ts_client(app_root: &Path, ir: &AppIr) -> io::Result<PathBuf> {
    let dest = app_root.join(GENERATED_CLIENT_TS);
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&dest, generate_ts_client(ir))?;
    Ok(dest)
}

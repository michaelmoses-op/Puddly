//! Opt-in scaffold: commit `AUTH_SCHEMA_SQL` as a reviewed migration file (Step 5 rec 6A).

use crate::AUTH_SCHEMA_SQL;
use puddly_core::{CLI_NAME, DISPLAY_NAME, MIGRATIONS_DIR};
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone)]
pub struct ScaffoldResult {
    pub path: PathBuf,
    pub created: bool,
    pub message: String,
}

/// Write `migrations/NNNN_puddly_auth.sql` if missing (does not overwrite).
pub fn scaffold_auth_migration(root: &Path) -> std::io::Result<ScaffoldResult> {
    let dir = root.join(MIGRATIONS_DIR);
    fs::create_dir_all(&dir)?;

    let existing: Vec<_> = fs::read_dir(&dir)?
        .filter_map(|e| e.ok())
        .filter(|e| {
            e.path()
                .extension()
                .and_then(|x| x.to_str())
                .map(|x| x == "sql")
                .unwrap_or(false)
        })
        .collect();

    // If any file already contains auth accounts table, skip.
    for e in &existing {
        if let Ok(text) = fs::read_to_string(e.path()) {
            if text.contains("puddly_auth_accounts") {
                return Ok(ScaffoldResult {
                    path: e.path(),
                    created: false,
                    message: format!(
                        "auth migration already present ({})",
                        e.path().display()
                    ),
                });
            }
        }
    }

    let next_n = existing.len() + 1;
    let filename = format!("{next_n:04}_puddly_auth.sql");
    let path = dir.join(&filename);
    let body = format!(
        "-- puddly migration {next_n:04}_puddly_auth\n\
         -- Generated by {DISPLAY_NAME} `{CLI_NAME} auth scaffold`; review before applying.\n\
         -- Opt-in framework auth tables (email/password + sessions).\n\
         \n\
         {AUTH_SCHEMA_SQL}\n"
    );
    fs::write(&path, body)?;
    Ok(ScaffoldResult {
        path: path.clone(),
        created: true,
        message: format!("wrote {MIGRATIONS_DIR}/{filename}"),
    })
}
